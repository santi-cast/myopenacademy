package dev.codeacademy.content;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.TimeUnit;
import java.util.function.Consumer;
import java.util.stream.Stream;

import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ObjectNode;

/**
 * The content of the tests: the kit's two example courses (cursos-ejemplo/, copied from a pinned kit commit) installed
 * with the real importer, «ejemplo» first and «ejemplo-destino» on top, exactly as an academy installs them. Generated
 * once per test JVM into the system temp area and removed when it exits; no test reads the academy's own content/.
 * Each course is committed to its own temporary repository with fixed names and dates, so every commit, and so every
 * generated byte, is the same on every run.
 */
public final class ExampleContent {

	/** The copies of the kit's example courses, relative to the backend working directory. */
	public static final Path COURSES = Path.of("../cursos-ejemplo");
	/** The folders under {@link #COURSES}, in install order. */
	public static final List<String> FOLDERS = List.of("bueno", "ejemplo-destino");

	public static final String COURSE = "ejemplo";
	public static final String DESTINATION = "ejemplo-destino";
	/** The available module of «ejemplo», with two exercises, a code folder and an image. */
	public static final String LESSON = "ejemplo.ficheros-json";
	/** The pending module of «ejemplo»: declared in curso.json, without a body. */
	public static final String PENDING = "ejemplo.ficheros-yaml";
	public static final String E01 = "ejemplo.ficheros-json.un-pedido";
	public static final String E02 = "ejemplo.ficheros-json.la-coma-de-mas";
	public static final String STAGE = "ejemplo.etapa.primer-catalogo";

	private static final JsonMapper JSON = JsonMapper.builder().build();

	private static Path root;

	private ExampleContent() {
	}

	/** The generated content root, read-only by convention: copy it with {@link #copyInto} before changing it. */
	public static synchronized Path root() {
		if (root == null) {
			try {
				Path temp = Files.createTempDirectory("myopenacademy-ejemplo-");
				Runtime.getRuntime().addShutdownHook(new Thread(() -> deleteTree(temp)));
				root = generate(temp);
			}
			catch (IOException ex) {
				throw new UncheckedIOException(ex);
			}
		}
		return root;
	}

	/** A writable copy of the generated content root at {@code target}, which must not exist yet. */
	public static Path copyInto(Path target) throws IOException {
		Path source = root();
		try (Stream<Path> files = Files.walk(source)) {
			for (Path file : files.toList()) {
				Path copy = target.resolve(source.relativize(file).toString());
				if (Files.isDirectory(file)) Files.createDirectories(copy);
				else Files.copy(file, copy);
			}
		}
		return target;
	}

	/** A writable copy of one installed example course, {@code course}, into the content root {@code root}. */
	public static void copyCourseInto(String course, Path root) throws IOException {
		Path source = root().resolve(course);
		try (Stream<Path> files = Files.walk(source)) {
			for (Path file : files.toList()) {
				Path copy = root.resolve(course).resolve(source.relativize(file).toString());
				if (Files.isDirectory(file)) Files.createDirectories(copy);
				else Files.copy(file, copy);
			}
		}
	}

	/** The pinned commit of the temporary repository of one example course, as recorded in its manifest. */
	public static synchronized String commit(String folder) {
		root();
		return commits.get(folder);
	}

	private static Map<String, String> commits;

	private static Path generate(Path temp) throws IOException {
		Path active = Files.createDirectory(temp.resolve("vacio"));
		Map<String, String> pinned = new LinkedHashMap<>();
		int step = 0;
		for (String folder : FOLDERS) {
			step++;
			Path output = temp.resolve("contenido-" + step);
			pinned.put(folder, install(COURSES.resolve(folder).toAbsolutePath().normalize(), temp.resolve(folder + ".git"),
				active, output, temp.resolve("informe-" + step + ".json")));
			active = output;
		}
		commits = Map.copyOf(pinned);
		return active;
	}

	/**
	 * One example course installed alone, with the real importer, from a copy of its folder whose curso.json
	 * {@code edit} changes: another version of the course, for the tests of an update. Works inside {@code work},
	 * which must exist and be empty, and returns the content root.
	 */
	public static Path installVariant(String folder, Consumer<ObjectNode> edit, Path work) throws IOException {
		Path course = work.resolve("fuente");
		Path source = COURSES.resolve(folder);
		try (Stream<Path> files = Files.walk(source)) {
			for (Path file : files.toList()) {
				Path copy = course.resolve(source.relativize(file).toString());
				if (Files.isDirectory(file)) Files.createDirectories(copy);
				else Files.copy(file, copy);
			}
		}
		Path descriptor = course.resolve("curso.json");
		ObjectNode curso = (ObjectNode) JSON.readTree(descriptor.toFile());
		edit.accept(curso);
		Files.writeString(descriptor, JSON.writerWithDefaultPrettyPrinter().writeValueAsString(curso) + "\n");
		Path output = work.resolve("contenido");
		install(course.toAbsolutePath(), work.resolve(folder + ".git"), Files.createDirectory(work.resolve("vacio")),
			output, work.resolve("informe.json"));
		return output;
	}

	/** Commits {@code course} into a new repository and installs it on top of {@code active}; returns the commit. */
	private static String install(Path course, Path repository, Path active, Path output, Path report) throws IOException {
		String commit = commitCourse(course, repository);
		ContentImportGenerator.Result result = ContentImportGenerator.generate(new ContentImportCli.Paths(active,
			repository, commit, output, report));
		if (!result.written()) {
			throw new IllegalStateException("the example course " + course + " does not install: " + result.findings());
		}
		return commit;
	}

	/** Commits the course folder as it is into a new bare repository, without touching the folder. */
	private static String commitCourse(Path course, Path repository) throws IOException {
		git(null, "init", "--bare", "--quiet", repository.toString());
		git(repository, "--work-tree=" + course, "add", "--all");
		git(repository, "--work-tree=" + course, "commit", "--quiet", "--message=ejemplo");
		return git(repository, "rev-parse", "HEAD").strip();
	}

	private static String git(Path repository, String... args) throws IOException {
		List<String> command = new ArrayList<>(List.of("git"));
		if (repository != null) command.add("--git-dir=" + repository);
		command.addAll(List.of(args));
		ProcessBuilder builder = new ProcessBuilder(command);
		// Nothing from the machine's Git configuration: same line endings, ignores and identity everywhere.
		builder.environment().putAll(Map.of("GIT_CONFIG_GLOBAL", "/dev/null", "GIT_CONFIG_NOSYSTEM", "1",
			"GIT_AUTHOR_NAME", "Fixture", "GIT_AUTHOR_EMAIL", "fixture@example.invalid",
			"GIT_COMMITTER_NAME", "Fixture", "GIT_COMMITTER_EMAIL", "fixture@example.invalid",
			"GIT_AUTHOR_DATE", "2026-01-01T00:00:00 +0000", "GIT_COMMITTER_DATE", "2026-01-01T00:00:00 +0000"));
		builder.redirectErrorStream(true);
		Process process = builder.start();
		process.getOutputStream().close();
		String out = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
		try {
			if (!process.waitFor(30, TimeUnit.SECONDS) || process.exitValue() != 0) {
				throw new IllegalStateException("git " + String.join(" ", args) + " failed: " + out);
			}
		}
		catch (InterruptedException ex) {
			Thread.currentThread().interrupt();
			throw new IllegalStateException(ex);
		}
		return out;
	}

	private static void deleteTree(Path path) {
		try (Stream<Path> files = Files.walk(path)) {
			files.sorted(Comparator.reverseOrder()).forEach(file -> file.toFile().delete());
		}
		catch (IOException ignored) {
			// Best effort at JVM exit; the directory lives in the system temp area.
		}
	}
}
